/**
 * Generates the compact catalogs shipped to runtime consumers.
 *
 * packages/core/locales/*.json remain the canonical Crowdin sources and keep
 * translator descriptions. Generated package catalogs retain the public
 * `{defaultMessage}` entry shape but omit translator-only metadata. The English
 * fallback also gets a string-only TypeScript map for the smallest default
 * bundle.
 */

import {spawn} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {gzipSync} from 'node:zlib';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {createPseudoCatalog} from '../packages/core/scripts/build-pseudo-locale.mjs';

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, '..');
const SOURCE_LOCALES_DIR = path.join(REPO_ROOT, 'packages', 'core', 'locales');
const SHIPPED_LOCALES_DIR = path.join(
  REPO_ROOT,
  'packages',
  'core',
  'runtime-locales',
);
const EN_RUNTIME_FILE = path.join(
  REPO_ROOT,
  'packages',
  'core',
  'src',
  'i18n',
  'enCatalog.generated.ts',
);
const EN_FILE = 'en.json';
const PSEUDO_FILE = 'pseudo.json';

export const MAX_RUNTIME_CATALOG_GZIP_BYTES = 10 * 1024;

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function validateEntry(key, entry) {
  if (
    entry === null ||
    typeof entry !== 'object' ||
    Array.isArray(entry) ||
    typeof entry.defaultMessage !== 'string'
  ) {
    throw new Error(`${key}: missing string "defaultMessage"`);
  }
}

/** Reduce a rich catalog to the strings used by the built-in English fallback. */
export function createRuntimeCatalog(sourceCatalog) {
  return Object.fromEntries(
    Object.entries(sourceCatalog).map(([key, entry]) => {
      validateEntry(key, entry);
      return [key, entry.defaultMessage];
    }),
  );
}

/** Preserve the public Catalog shape while removing translator-only metadata. */
export function createPublishedCatalog(sourceCatalog) {
  return Object.fromEntries(
    Object.entries(sourceCatalog).map(([key, entry]) => {
      validateEntry(key, entry);
      return [key, {defaultMessage: entry.defaultMessage}];
    }),
  );
}

export function getRuntimeCatalogGzipBytes(runtimeCatalog) {
  return gzipSync(JSON.stringify(runtimeCatalog)).byteLength;
}

export function assertRuntimeCatalogSize(runtimeCatalog, label = 'Catalog') {
  const gzipBytes = getRuntimeCatalogGzipBytes(runtimeCatalog);
  if (gzipBytes > MAX_RUNTIME_CATALOG_GZIP_BYTES) {
    throw new Error(
      `${label} is ${gzipBytes} bytes gzip, above the ${MAX_RUNTIME_CATALOG_GZIP_BYTES}-byte limit. ` +
        'Revisit coarse catalog splitting before increasing the limit.',
    );
  }
  return gzipBytes;
}

export async function renderRuntimeCatalogFile(runtimeCatalog) {
  const {format, resolveConfig} = await import('prettier');
  const source = `// Copyright (c) Meta Platforms, Inc. and affiliates.\n\n/**\n * @generated by scripts/generate-i18n-runtime.mjs from packages/core/locales/en.json.\n * Translator descriptions remain in the source catalog and must not be copied here.\n * Do not edit by hand. Run \`pnpm generate:i18n-runtime\` instead.\n */\n\nexport const enCatalog: Readonly<Record<string, string>> = ${JSON.stringify(runtimeCatalog)};\n`;
  const prettierConfig = await resolveConfig(EN_RUNTIME_FILE);
  return format(source, {...prettierConfig, filepath: EN_RUNTIME_FILE});
}

function readSourceCatalogs() {
  return Object.fromEntries(
    fs
      .readdirSync(SOURCE_LOCALES_DIR, {withFileTypes: true})
      .filter(
        entry =>
          entry.isFile() &&
          entry.name.endsWith('.json') &&
          entry.name !== PSEUDO_FILE,
      )
      .map(entry => [
        entry.name,
        readJson(path.join(SOURCE_LOCALES_DIR, entry.name)),
      ])
      .sort(([left], [right]) => left.localeCompare(right)),
  );
}

export function createPublishedCatalogs(sourceCatalogs) {
  const published = Object.fromEntries(
    Object.entries(sourceCatalogs).map(([file, catalog]) => [
      file,
      createPublishedCatalog(catalog),
    ]),
  );
  const english = sourceCatalogs[EN_FILE];
  if (!english) throw new Error(`Missing source catalog: ${EN_FILE}`);
  published[PSEUDO_FILE] = createPseudoCatalog(english);
  return published;
}

function writeIfChanged(file, content) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) {
    return false;
  }
  fs.writeFileSync(file, content);
  return true;
}

function removeStaleCatalogs(expectedFiles) {
  if (!fs.existsSync(SHIPPED_LOCALES_DIR)) return 0;
  let removed = 0;
  for (const entry of fs.readdirSync(SHIPPED_LOCALES_DIR, {
    withFileTypes: true,
  })) {
    if (
      entry.isFile() &&
      entry.name.endsWith('.json') &&
      !expectedFiles.has(entry.name)
    ) {
      fs.rmSync(path.join(SHIPPED_LOCALES_DIR, entry.name));
      removed += 1;
    }
  }
  return removed;
}

export function isSourceLocaleFile(file) {
  return (
    typeof file === 'string' && file.endsWith('.json') && file !== PSEUDO_FILE
  );
}

export async function generateRuntimeCatalogs({check = false} = {}) {
  const sourceCatalogs = readSourceCatalogs();
  const english = sourceCatalogs[EN_FILE];
  if (!english) throw new Error(`Missing source catalog: ${EN_FILE}`);

  const englishRuntime = createRuntimeCatalog(english);
  const englishGzipBytes = assertRuntimeCatalogSize(
    englishRuntime,
    'English fallback catalog',
  );
  const publishedCatalogs = createPublishedCatalogs(sourceCatalogs);
  let publishedGzipBytes = 0;
  for (const [file, catalog] of Object.entries(publishedCatalogs)) {
    publishedGzipBytes += assertRuntimeCatalogSize(catalog, file);
  }

  if (check) {
    console.log(
      `✓ ${Object.keys(publishedCatalogs).length} runtime locale catalogs omit translator metadata ` +
        `(${publishedGzipBytes} aggregate gzip bytes); English fallback is ${englishGzipBytes} bytes gzip`,
    );
    return;
  }

  const englishOutput = await renderRuntimeCatalogFile(englishRuntime);
  fs.mkdirSync(SHIPPED_LOCALES_DIR, {recursive: true});
  let changed = writeIfChanged(EN_RUNTIME_FILE, englishOutput) ? 1 : 0;
  const expectedFiles = new Set(Object.keys(publishedCatalogs));
  const removed = removeStaleCatalogs(expectedFiles);
  for (const [file, catalog] of Object.entries(publishedCatalogs)) {
    const output = `${JSON.stringify(catalog, null, 2)}\n`;
    if (writeIfChanged(path.join(SHIPPED_LOCALES_DIR, file), output)) {
      changed += 1;
    }
  }

  console.log(
    `Generated ${Object.keys(publishedCatalogs).length} runtime locale catalogs ` +
      `(${publishedGzipBytes} aggregate gzip bytes; ${changed} changed, ${removed} stale removed); ` +
      `English fallback is ${englishGzipBytes} bytes gzip`,
  );
}

export function createSpawnInvocation(
  command,
  platform = process.platform,
  commandShell = process.env.ComSpec ?? 'cmd.exe',
) {
  if (platform !== 'win32') {
    return {file: command[0], args: command.slice(1)};
  }
  const unsafe = command.find(arg => !/^[A-Za-z0-9_@./:\\=-]+$/.test(arg));
  if (unsafe !== undefined) {
    throw new Error(
      `Windows watch commands cannot contain spaces or shell metacharacters: ${unsafe}`,
    );
  }
  return {
    file: commandShell,
    args: ['/d', '/s', '/c', command.join(' ')],
  };
}

async function watchRuntimeCatalogs(command) {
  await generateRuntimeCatalogs();

  let debounce;
  let regeneration = Promise.resolve();
  const watcher = fs.watch(SOURCE_LOCALES_DIR, (_event, file) => {
    const fileName = file == null ? null : String(file);
    if (fileName !== null && !isSourceLocaleFile(fileName)) return;
    clearTimeout(debounce);
    debounce = setTimeout(() => {
      regeneration = regeneration
        .then(() => generateRuntimeCatalogs())
        .catch(error => {
          const message =
            error instanceof Error ? error.message : String(error);
          console.error(
            `Could not regenerate runtime locale catalogs: ${message}`,
          );
        });
    }, 75);
  });

  const spawnOptions = {env: process.env, stdio: 'inherit'};
  const invocation = createSpawnInvocation(command);
  const child = spawn(invocation.file, invocation.args, spawnOptions);
  const forwardInterrupt = () => child.kill('SIGINT');
  const forwardTermination = () => child.kill('SIGTERM');
  process.on('SIGINT', forwardInterrupt);
  process.on('SIGTERM', forwardTermination);

  try {
    return await new Promise((resolve, reject) => {
      child.once('error', reject);
      child.once('exit', (code, signal) => resolve(signal ? 1 : (code ?? 1)));
    });
  } finally {
    clearTimeout(debounce);
    watcher.close();
    process.removeListener('SIGINT', forwardInterrupt);
    process.removeListener('SIGTERM', forwardTermination);
  }
}

async function main() {
  const args = process.argv.slice(2);
  if (args.includes('--watch')) {
    const separator = args.indexOf('--');
    const command = separator === -1 ? [] : args.slice(separator + 1);
    if (command.length === 0) {
      throw new Error('`--watch` requires a command after `--`');
    }
    process.exitCode = await watchRuntimeCatalogs(command);
    return;
  }
  await generateRuntimeCatalogs({check: args.includes('--check')});
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  try {
    await main();
  } catch (error) {
    if (!process.argv.slice(2).includes('--best-effort')) throw error;
    const message = error instanceof Error ? error.message : String(error);
    console.warn(`Could not generate runtime locale catalogs: ${message}`);
  }
}
